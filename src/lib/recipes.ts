const GLUTEN = new Set(["penne", "spaghetti", "tortilla", "chleb", "bulka"]);
const LACTOSE = new Set(["mleko", "jogurt", "gouda", "smietana", "maslo", "feta"]);
const EGGS = new Set(["jaja"]);
const FISH = new Set(["losos", "dorsz"]);
const SOY = new Set(["tofu"]);

function allergens(meal: Meal): Allergen[] {
  const ids = meal.paid.map(([id]) => id);
  const list: Allergen[] = [];
  if (ids.some((id) => GLUTEN.has(id))) list.push("gluten");
  if (ids.some((id) => LACTOSE.has(id))) list.push("lactose");
  if (ids.some((id) => EGGS.has(id))) list.push("eggs");
  if (ids.some((id) => FISH.has(id))) list.push("fish");
  if (ids.some((id) => SOY.has(id)) || meal.pantry.includes("Соевый соус")) list.push("soy");
  return list;
}

